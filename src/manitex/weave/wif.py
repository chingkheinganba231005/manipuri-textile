"""WIF (Weaving Information File, version 1.1) writer and reader.

WIF is the interchange format understood by most weaving software (e.g. WeaveIt,
Fiberworks, WeavePoint, pixeLoom, handweaving.net) and by several computer-assisted
looms.  The writer emits a minimal threading (one shaft per distinct end behaviour) and
a LIFTPLAN; optionally TIEUP / TREADLING are included as well when the number of
distinct sheds is small enough for a treadle loom.
"""

from __future__ import annotations

import datetime as _dt
from pathlib import Path

import numpy as np

from manitex import __version__
from manitex.weave.draft import PICK_SUPPLEMENTARY, WeaveDraft

_TRUE = {"true", "yes", "on", "1"}


def _fmt_list(idx: np.ndarray) -> str:
    return ",".join(str(int(i) + 1) for i in idx)


def to_wif(
    draft: WeaveDraft,
    title: str = "manitex design",
    author: str = "",
    include_treadling: bool | None = None,
    max_treadles: int = 24,
    units: str = "centimeters",
    ends_per_unit: float | None = None,
    picks_per_unit: float | None = None,
    notes: list[str] | None = None,
) -> str:
    """Serialise a draft as a WIF 1.1 string."""
    threading, lifts = draft.threading()
    n_shafts = lifts.shape[1]
    tieup = treadling = None
    if include_treadling is None:
        _, tu, tr = draft.treadling()
        include_treadling = tu.shape[0] <= max_treadles
        if include_treadling:
            tieup, treadling = tu, tr
    elif include_treadling:
        _, tieup, treadling = draft.treadling()

    used = sorted(set(draft.warp_colors.tolist()) | set(draft.weft_colors.tolist()))
    if draft.inlay is not None:
        used = sorted(set(used) | set(draft.inlay[draft.inlay >= 0].tolist()))
    # WIF colour indices are 1-based entries in the colour table; keep palette indices.
    pal = draft.palette
    lines: list[str] = []
    add = lines.append
    add("[WIF]")
    add("Version=1.1")
    add("Date=April 20, 1997")
    add("Developers=wif@mhsoft.com")
    add("Source Program=manitex")
    add(f"Source Version={__version__}")
    add("")
    add("[CONTENTS]")
    sections = ["COLOR PALETTE", "TEXT", "WEAVING", "WARP", "WEFT", "COLOR TABLE", "THREADING", "LIFTPLAN",
                "WARP COLORS", "WEFT COLORS", "NOTES"]
    if include_treadling:
        sections += ["TIEUP", "TREADLING"]
    for s in sections:
        add(f"{s}=true")
    add("")
    add("[TEXT]")
    add(f"Title={title}")
    if author:
        add(f"Author={author}")
    add("")
    note_lines = list(notes or [])
    note_lines.append(f"Generated by manitex {__version__} on {_dt.date.today().isoformat()}.")
    note_lines.append("End 1 is the leftmost end seen from the face; pick 1 is the first pick woven.")
    n_supp = int((draft.pick_kind == PICK_SUPPLEMENTARY).sum())
    if n_supp:
        note_lines.append(f"{n_supp} of {draft.n_picks} picks are supplementary (pattern) wefts; "
                          "use a thicker / softer yarn for them.")
    if draft.inlay is not None:
        note_lines.append("Pattern picks are discontinuous inlay: WEFT COLORS lists the main colour of each "
                          "inlay pick; see the manitex chart for the colour of each region.")
    add("[NOTES]")
    for i, s in enumerate(note_lines, 1):
        add(f"{i}={s.replace(chr(10), ' ')}")
    add("")
    add("[COLOR PALETTE]")
    add(f"Entries={pal.shape[0]}")
    add("Range=0,255")
    add("")
    add("[COLOR TABLE]")
    for i, c in enumerate(pal, 1):
        add(f"{i}={int(c[0])},{int(c[1])},{int(c[2])}")
    add("")
    add("[WEAVING]")
    add(f"Shafts={n_shafts}")
    add(f"Treadles={tieup.shape[0] if include_treadling else n_shafts}")
    add("Rising Shed=true")
    add("")
    warp_default = int(np.bincount(draft.warp_colors).argmax()) if draft.n_ends else 0
    weft_default = int(np.bincount(draft.weft_colors).argmax()) if draft.n_picks else 0
    add("[WARP]")
    add(f"Threads={draft.n_ends}")
    add(f"Color={warp_default + 1}")
    add(f"Units={units}")
    if ends_per_unit:
        add(f"Spacing={1.0 / ends_per_unit:.4f}")
        add(f"Thickness={1.0 / ends_per_unit:.4f}")
    add("")
    add("[WEFT]")
    add(f"Threads={draft.n_picks}")
    add(f"Color={weft_default + 1}")
    add(f"Units={units}")
    if picks_per_unit:
        add(f"Spacing={1.0 / picks_per_unit:.4f}")
        add(f"Thickness={1.0 / picks_per_unit:.4f}")
    add("")
    add("[THREADING]")
    for e, s in enumerate(threading, 1):
        add(f"{e}={int(s) + 1}")
    add("")
    add("[LIFTPLAN]")
    for p in range(draft.n_picks):
        raised = np.flatnonzero(lifts[p])
        if raised.size:
            add(f"{p + 1}={_fmt_list(raised)}")
    add("")
    if include_treadling and tieup is not None and treadling is not None:
        add("[TIEUP]")
        for t in range(tieup.shape[0]):
            shafts = np.flatnonzero(tieup[t])
            if shafts.size:
                add(f"{t + 1}={_fmt_list(shafts)}")
        add("")
        add("[TREADLING]")
        for p, t in enumerate(treadling, 1):
            add(f"{p}={int(t) + 1}")
        add("")
    add("[WARP COLORS]")
    for e, c in enumerate(draft.warp_colors, 1):
        if int(c) != warp_default:
            add(f"{e}={int(c) + 1}")
    add("")
    add("[WEFT COLORS]")
    for p, c in enumerate(draft.weft_colors, 1):
        if int(c) != weft_default:
            add(f"{p}={int(c) + 1}")
    add("")
    return "\r\n".join(lines)


def save_wif(draft: WeaveDraft, path: str | Path, **kw) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(to_wif(draft, **kw), encoding="utf-8", newline="")
    return path


