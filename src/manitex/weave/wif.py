def _parse_ini(text: str) -> dict[str, dict[str, str]]:
    sections: dict[str, dict[str, str]] = {}
    cur: dict[str, str] | None = None
    for raw in text.splitlines():
        line = raw.strip()
        if not line or line.startswith(";"):
            continue
        if line.startswith("[") and "]" in line:
            name = line[1 : line.index("]")].strip().upper()
            cur = sections.setdefault(name, {})
            continue
        if cur is None or "=" not in line:
            continue
        key, _, val = line.partition("=")
        cur[key.strip().lower()] = val.strip()
    return sections


def _ints(s: str) -> list[int]:
    return [int(float(x)) for x in s.replace(" ", "").split(",") if x != ""]


def read_wif(source: str | Path) -> WeaveDraft:
    """Parse a WIF file (path or text) into a :class:`WeaveDraft`.

    Supports LIFTPLAN or TIEUP+TREADLING, rising or sinking shed, multiple shafts per end,
    colour tables with any ``Range``.  Missing colours default to black warp / white weft.
    """
    text = Path(source).read_text(encoding="utf-8", errors="replace") if isinstance(source, Path) or (
        isinstance(source, str) and "\n" not in source and Path(source).exists()) else str(source)
    s = _parse_ini(text)
    if "WIF" not in s:
        raise ValueError("not a WIF file (missing [WIF] section)")
    weaving = s.get("WEAVING", {})
    warp = s.get("WARP", {})
    weft = s.get("WEFT", {})
    n_ends = int(float(warp.get("threads", "0")))
    n_picks = int(float(weft.get("threads", "0")))
    threading = s.get("THREADING", {})
    if n_ends == 0 and threading:
        n_ends = max(int(k) for k in threading)
    n_shafts = int(float(weaving.get("shafts", "0") or 0))
    rising = weaving.get("rising shed", "true").strip().lower() in _TRUE

    # threading: end -> list of shafts (1-based)
    end_shafts: list[list[int]] = [[] for _ in range(n_ends)]
    for k, v in threading.items():
        e = int(k) - 1
        if 0 <= e < n_ends:
            end_shafts[e] = [x for x in _ints(v) if x > 0]
    if n_shafts == 0:
        n_shafts = max([max(x) for x in end_shafts if x] or [1])

    # shaft lifts per pick
    pick_shafts: dict[int, list[int]] = {}
    if "LIFTPLAN" in s:
        for k, v in s["LIFTPLAN"].items():
            pick_shafts[int(k) - 1] = _ints(v)
    elif "TREADLING" in s:
        tieup = {int(k): _ints(v) for k, v in s.get("TIEUP", {}).items()}
        if not rising:
            all_shafts = set(range(1, n_shafts + 1))
            tieup = {t: sorted(all_shafts - set(sh)) for t, sh in tieup.items()}
        for k, v in s["TREADLING"].items():
            shafts: set[int] = set()
            for t in _ints(v):
                shafts |= set(tieup.get(t, []))
            pick_shafts[int(k) - 1] = sorted(shafts)
    if n_picks == 0 and pick_shafts:
        n_picks = max(pick_shafts) + 1

    lift_sh = np.zeros((n_picks, n_shafts + 1), dtype=bool)
    for p, shafts in pick_shafts.items():
        if 0 <= p < n_picks:
            for x in shafts:
                if 0 < x <= n_shafts:
                    lift_sh[p, x] = True
    liftplan = np.zeros((n_picks, n_ends), dtype=np.uint8)
    for e, shafts in enumerate(end_shafts):
        if shafts:
            liftplan[:, e] = lift_sh[:, shafts].any(axis=1)

    # colours
    rng_lo, rng_hi = 0.0, 255.0
    if "COLOR PALETTE" in s and "range" in s["COLOR PALETTE"]:
        lo_hi = [float(x) for x in s["COLOR PALETTE"]["range"].split(",")]
        if len(lo_hi) == 2 and lo_hi[1] > lo_hi[0]:
            rng_lo, rng_hi = lo_hi
    table = {int(k): [float(x) for x in v.split(",")[:3]] for k, v in s.get("COLOR TABLE", {}).items()}
    if table:
        n_col = max(table)
        palette = np.zeros((n_col, 3))
        for k, rgb in table.items():
            palette[k - 1] = [(c - rng_lo) / (rng_hi - rng_lo) * 255.0 for c in rgb]
        palette = np.clip(np.rint(palette), 0, 255).astype(np.uint8)
        warp_default = int(float(warp.get("color", "1").split(",")[0])) - 1
        weft_default = int(float(weft.get("color", "1").split(",")[0])) - 1
    else:
        palette = np.array([[20, 20, 20], [240, 240, 240]], dtype=np.uint8)
        warp_default, weft_default = 0, 1
    warp_colors = np.full(n_ends, max(warp_default, 0), np.int32)
    weft_colors = np.full(n_picks, max(weft_default, 0), np.int32)
    for k, v in s.get("WARP COLORS", {}).items():
        e = int(k) - 1
        if 0 <= e < n_ends:
            warp_colors[e] = int(float(v.split(",")[0])) - 1
    for k, v in s.get("WEFT COLORS", {}).items():
        p = int(k) - 1
        if 0 <= p < n_picks:
            weft_colors[p] = int(float(v.split(",")[0])) - 1
    k_max = palette.shape[0]
    warp_colors = np.clip(warp_colors, 0, k_max - 1)
    weft_colors = np.clip(weft_colors, 0, k_max - 1)
    title = s.get("TEXT", {}).get("title", "")
    return WeaveDraft(liftplan, warp_colors, weft_colors, palette, meta={"title": title, "source": "wif"})
